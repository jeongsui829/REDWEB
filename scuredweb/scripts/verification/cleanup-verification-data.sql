-- Usage: @cleanup-verification-data.sql USER_ID POST_ID ATTACH_ID REPORT_ID MESSAGE_ID ENTRY_ID
-- Supply only IDs created by the verification run. Use -1 for an unused item.
DEFINE VERIFY_USER_ID = &1
DEFINE VERIFY_POST_ID = &2
DEFINE VERIFY_ATTACH_ID = &3
DEFINE VERIFY_REPORT_ID = &4
DEFINE VERIFY_MESSAGE_ID = &5
DEFINE VERIFY_ENTRY_ID = &6

SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DELETE FROM RW_NOTIFICATION WHERE USER_ID = &&VERIFY_USER_ID;
DELETE FROM RW_MESSAGE WHERE MESSAGE_ID = &&VERIFY_MESSAGE_ID;
DELETE FROM RW_MESSAGE WHERE SENDER_USER_ID = &&VERIFY_USER_ID OR RECEIVER_USER_ID = &&VERIFY_USER_ID;
DELETE FROM RW_GUESTBOOK WHERE ENTRY_ID = &&VERIFY_ENTRY_ID;
DELETE FROM RW_GUESTBOOK WHERE OWNER_USER_ID = &&VERIFY_USER_ID OR WRITER_USER_ID = &&VERIFY_USER_ID;
DELETE FROM RW_REPORT WHERE REPORT_ID = &&VERIFY_REPORT_ID;
DELETE FROM RW_REPORT WHERE REPORTER_ID = &&VERIFY_USER_ID;
DELETE FROM RW_REPORT WHERE TARGET_TYPE = 'USER' AND TARGET_ID = &&VERIFY_USER_ID;
DELETE FROM RW_REPORT WHERE TARGET_TYPE = 'POST' AND TARGET_ID = &&VERIFY_POST_ID;
DELETE FROM RW_RECENT_VIEW WHERE USER_ID = &&VERIFY_USER_ID OR POST_ID = &&VERIFY_POST_ID;
DELETE FROM RW_POST_REACTION WHERE USER_ID = &&VERIFY_USER_ID OR POST_ID = &&VERIFY_POST_ID;
DELETE FROM RW_POST_TAG WHERE POST_ID = &&VERIFY_POST_ID;
DELETE FROM RW_COMMENT WHERE POST_ID = &&VERIFY_POST_ID;
DELETE FROM RW_ATTACHMENT WHERE ATTACH_ID = &&VERIFY_ATTACH_ID;
DELETE FROM RW_ATTACHMENT WHERE POST_ID = &&VERIFY_POST_ID OR UPLOADER_ID = &&VERIFY_USER_ID;
DELETE FROM RW_POST WHERE POST_ID = &&VERIFY_POST_ID AND USER_ID = &&VERIFY_USER_ID;
DELETE FROM RW_USER_AUTH_LOG WHERE USER_ID = &&VERIFY_USER_ID;
DELETE FROM RW_ADMIN_USER_ROLE WHERE USER_ID = &&VERIFY_USER_ID;
DELETE FROM RW_ADMIN_ACTION_LOG WHERE ADMIN_USER_ID = &&VERIFY_USER_ID;
UPDATE RW_ACCESS_LOG SET USER_ID = NULL WHERE USER_ID = &&VERIFY_USER_ID;
UPDATE RW_ERROR_LOG SET USER_ID = NULL WHERE USER_ID = &&VERIFY_USER_ID;

DECLARE
    v_table_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_table_count
      FROM USER_TABLES
     WHERE TABLE_NAME = 'RW_PASSWORD_RESET_TOKEN';
    IF v_table_count > 0 THEN
        EXECUTE IMMEDIATE 'DELETE FROM RW_PASSWORD_RESET_TOKEN WHERE USER_ID = :1'
            USING &&VERIFY_USER_ID;
    END IF;
END;
/

DELETE FROM RW_USER WHERE USER_ID = &&VERIFY_USER_ID;
COMMIT;

PROMPT Verification rows for the supplied exact IDs were removed.
