UPDATE RW_USER
   SET PROFILE_IMAGE_PATH = SUBSTR(PROFILE_IMAGE_PATH, INSTR(PROFILE_IMAGE_PATH, '/profile/image'))
 WHERE INSTR(PROFILE_IMAGE_PATH, '/profile/image?savedName=') > 0
   AND INSTR(PROFILE_IMAGE_PATH, '/profile/image?savedName=') <> 1;

UPDATE RW_USER
   SET PROFILE_IMAGE_PATH = '/profile/image?savedName=' || REGEXP_SUBSTR(PROFILE_IMAGE_PATH, '[^/\\]+$')
 WHERE INSTR(PROFILE_IMAGE_PATH, '/uploads/profiles/') > 0;

UPDATE RW_POST
   SET CONTENT = REGEXP_REPLACE(CONTENT, 'src="[^"]*/files/image\?savedName=', 'src="/files/image?savedName=')
 WHERE REGEXP_LIKE(CONTENT, 'src="[^"]*/files/image\?savedName=');

COMMIT;
