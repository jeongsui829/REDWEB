DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'RW_PASSWORD_RESET_TOKEN' AND COLUMN_NAME = 'USED_AT';
    IF v_count = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE RW_PASSWORD_RESET_TOKEN ADD USED_AT TIMESTAMP'; END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_INDEXES
     WHERE INDEX_NAME = 'UX_RW_PASSWORD_RESET_TOKEN_HASH';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UX_RW_PASSWORD_RESET_TOKEN_HASH ON RW_PASSWORD_RESET_TOKEN (TOKEN_HASH)';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
    v_start NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_RW_MESSAGE';
    IF v_count = 0 THEN EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_RW_MESSAGE START WITH 1 INCREMENT BY 1 NOCACHE'; END IF;

    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_RW_GUESTBOOK';
    IF v_count = 0 THEN EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_RW_GUESTBOOK START WITH 1 INCREMENT BY 1 NOCACHE'; END IF;

    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_RW_PASSWORD_RESET_TOKEN';
    IF v_count = 0 THEN EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_RW_PASSWORD_RESET_TOKEN START WITH 1 INCREMENT BY 1 NOCACHE'; END IF;

    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_RW_USER';
    IF v_count = 0 THEN
        SELECT NVL(MAX(USER_ID), 0) + 1 INTO v_start FROM RW_USER;
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_RW_USER START WITH ' || v_start || ' INCREMENT BY 1 NOCACHE';
    END IF;
END;
/

