DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'RW_USER' AND COLUMN_NAME = 'BIO';
    IF v_count = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE RW_USER ADD BIO VARCHAR2(1000)'; END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'RW_USER' AND COLUMN_NAME = 'SECURITY_QUESTION';
    IF v_count = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE RW_USER ADD SECURITY_QUESTION VARCHAR2(300)'; END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'RW_USER' AND COLUMN_NAME = 'SECURITY_ANSWER';
    IF v_count = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE RW_USER ADD SECURITY_ANSWER VARCHAR2(300)'; END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'RW_USER' AND COLUMN_NAME = 'SUSPENDED_UNTIL';
    IF v_count = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE RW_USER ADD SUSPENDED_UNTIL TIMESTAMP'; END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'RW_REPORT' AND COLUMN_NAME = 'PENALTY_SUMMARY';
    IF v_count = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE RW_REPORT ADD PENALTY_SUMMARY VARCHAR2(300)'; END IF;
END;
