DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'RW_PASSWORD_RESET_TOKEN';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE RW_PASSWORD_RESET_TOKEN (
                TOKEN_ID NUMBER PRIMARY KEY,
                USER_ID NUMBER NOT NULL,
                TOKEN_HASH VARCHAR2(300) NOT NULL,
                EXPIRES_AT TIMESTAMP NOT NULL,
                USED_YN CHAR(1) DEFAULT ''N'' NOT NULL,
                USED_AT TIMESTAMP,
                CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT FK_RW_PASSWORD_RESET_TOKEN_USER FOREIGN KEY (USER_ID) REFERENCES RW_USER (USER_ID)
            )';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'RW_MESSAGE';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE RW_MESSAGE (
                MESSAGE_ID NUMBER PRIMARY KEY,
                SENDER_USER_ID NUMBER NOT NULL,
                RECEIVER_USER_ID NUMBER NOT NULL,
                TITLE VARCHAR2(200) NOT NULL,
                CONTENT VARCHAR2(2000) NOT NULL,
                READ_YN CHAR(1) DEFAULT ''N'' NOT NULL,
                CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT FK_RW_MESSAGE_SENDER FOREIGN KEY (SENDER_USER_ID) REFERENCES RW_USER (USER_ID),
                CONSTRAINT FK_RW_MESSAGE_RECEIVER FOREIGN KEY (RECEIVER_USER_ID) REFERENCES RW_USER (USER_ID)
            )';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'RW_GUESTBOOK';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE RW_GUESTBOOK (
                ENTRY_ID NUMBER PRIMARY KEY,
                OWNER_USER_ID NUMBER NOT NULL,
                WRITER_USER_ID NUMBER NOT NULL,
                CONTENT VARCHAR2(2000) NOT NULL,
                CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT FK_RW_GUESTBOOK_OWNER FOREIGN KEY (OWNER_USER_ID) REFERENCES RW_USER (USER_ID),
                CONSTRAINT FK_RW_GUESTBOOK_WRITER FOREIGN KEY (WRITER_USER_ID) REFERENCES RW_USER (USER_ID)
            )';
    END IF;
END;
