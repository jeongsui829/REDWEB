-- Read-only Oracle diagnostics for board persistence and list/detail dependencies.
-- Run while connected as the application schema. Set LOGIN_USER_ID to the
-- authenticated session user being tested.

DEFINE LOGIN_USER_ID = 1

SELECT USER,
       SYS_CONTEXT('USERENV', 'SERVICE_NAME') AS SERVICE_NAME,
       SYS_CONTEXT('USERENV', 'CON_NAME') AS CON_NAME
FROM DUAL;

SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME IN (
    'RW_USER',
    'RW_BOARD',
    'RW_CATEGORY',
    'RW_POST',
    'RW_POST_REACTION',
    'RW_ATTACHMENT'
)
ORDER BY TABLE_NAME;

SELECT SEQUENCE_NAME, LAST_NUMBER
FROM USER_SEQUENCES
WHERE SEQUENCE_NAME IN ('SEQ_RW_POST', 'SEQ_RW_ATTACHMENT')
ORDER BY SEQUENCE_NAME;

SELECT BOARD_ID, BOARD_CODE, BOARD_NAME, ACTIVE_YN
FROM RW_BOARD
ORDER BY BOARD_ID;

SELECT COUNT(*) AS POST_COUNT
FROM RW_POST;

SELECT MAX(POST_ID) AS MAX_POST_ID
FROM RW_POST;

SELECT POST_ID, BOARD_ID, USER_ID, TITLE, STATUS, CREATED_AT
FROM RW_POST
ORDER BY CREATED_AT DESC
FETCH FIRST 20 ROWS ONLY;

SELECT USER_ID, LOGIN_ID, NICKNAME, STATUS
FROM RW_USER
WHERE USER_ID = &LOGIN_USER_ID;

SELECT P.POST_ID,
       P.USER_ID,
       P.TITLE,
       P.STATUS,
       P.CREATED_AT,
       U.NICKNAME,
       B.BOARD_NAME,
       C.CATEGORY_NAME,
       (SELECT COUNT(*)
          FROM RW_POST_REACTION R
         WHERE R.POST_ID = P.POST_ID
           AND R.REACTION_TYPE = 'LIKE') AS LIKE_COUNT
FROM RW_POST P
JOIN RW_USER U ON P.USER_ID = U.USER_ID
JOIN RW_BOARD B ON P.BOARD_ID = B.BOARD_ID
LEFT JOIN RW_CATEGORY C ON P.CATEGORY_ID = C.CATEGORY_ID
ORDER BY P.CREATED_AT DESC
FETCH FIRST 20 ROWS ONLY;

