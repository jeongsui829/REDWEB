CREATE TABLE RW_USER (
    USER_ID NUMBER PRIMARY KEY,
    LOGIN_ID VARCHAR2(50) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    USER_NAME VARCHAR2(100) NOT NULL,
    NICKNAME VARCHAR2(100) NOT NULL UNIQUE,
    EMAIL VARCHAR2(150) NOT NULL UNIQUE,
    PHONE VARCHAR2(30),
    PROFILE_IMAGE_PATH VARCHAR2(300),
    BIO VARCHAR2(1000),
    SECURITY_QUESTION VARCHAR2(300),
    SECURITY_ANSWER VARCHAR2(300),
    SUSPENDED_UNTIL TIMESTAMP,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    ROLE_CODE VARCHAR2(30) DEFAULT 'MEMBER' NOT NULL,
    EMAIL_VERIFIED_YN CHAR(1) DEFAULT 'N' NOT NULL,
    LAST_LOGIN_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE RW_BOARD (
    BOARD_ID NUMBER PRIMARY KEY,
    BOARD_CODE VARCHAR2(50) NOT NULL UNIQUE,
    BOARD_NAME VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(400),
    ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
    SORT_ORDER NUMBER DEFAULT 0 NOT NULL
);

CREATE TABLE RW_CATEGORY (
    CATEGORY_ID NUMBER PRIMARY KEY,
    BOARD_ID NUMBER NOT NULL,
    CATEGORY_NAME VARCHAR2(100) NOT NULL,
    SORT_ORDER NUMBER DEFAULT 0 NOT NULL,
    ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT FK_RW_CATEGORY_BOARD FOREIGN KEY (BOARD_ID) REFERENCES RW_BOARD (BOARD_ID)
);

CREATE TABLE RW_POST (
    POST_ID NUMBER PRIMARY KEY,
    BOARD_ID NUMBER NOT NULL,
    CATEGORY_ID NUMBER,
    USER_ID NUMBER NOT NULL,
    TITLE VARCHAR2(200) NOT NULL,
    CONTENT CLOB NOT NULL,
    VIEW_COUNT NUMBER DEFAULT 0 NOT NULL,
    LIKE_COUNT NUMBER DEFAULT 0 NOT NULL,
    COMMENT_COUNT NUMBER DEFAULT 0 NOT NULL,
    NOTICE_YN CHAR(1) DEFAULT 'N' NOT NULL,
    PINNED_YN CHAR(1) DEFAULT 'N' NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'PUBLIC' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_RW_POST_BOARD FOREIGN KEY (BOARD_ID) REFERENCES RW_BOARD (BOARD_ID),
    CONSTRAINT FK_RW_POST_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES RW_CATEGORY (CATEGORY_ID),
    CONSTRAINT FK_RW_POST_USER FOREIGN KEY (USER_ID) REFERENCES RW_USER (USER_ID)
);

CREATE TABLE RW_COMMENT (
    COMMENT_ID NUMBER PRIMARY KEY,
    POST_ID NUMBER NOT NULL,
    USER_ID NUMBER NOT NULL,
    PARENT_COMMENT_ID NUMBER,
    CONTENT VARCHAR2(2000) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_RW_COMMENT_POST FOREIGN KEY (POST_ID) REFERENCES RW_POST (POST_ID),
    CONSTRAINT FK_RW_COMMENT_USER FOREIGN KEY (USER_ID) REFERENCES RW_USER (USER_ID),
    CONSTRAINT FK_RW_COMMENT_PARENT FOREIGN KEY (PARENT_COMMENT_ID) REFERENCES RW_COMMENT (COMMENT_ID)
);

CREATE TABLE RW_TAG (
    TAG_ID NUMBER PRIMARY KEY,
    TAG_NAME VARCHAR2(100) NOT NULL UNIQUE,
    USE_COUNT NUMBER DEFAULT 0 NOT NULL
);

CREATE TABLE RW_POST_TAG (
    POST_TAG_ID NUMBER PRIMARY KEY,
    POST_ID NUMBER NOT NULL,
    TAG_ID NUMBER NOT NULL,
    CONSTRAINT FK_RW_POST_TAG_POST FOREIGN KEY (POST_ID) REFERENCES RW_POST (POST_ID),
    CONSTRAINT FK_RW_POST_TAG_TAG FOREIGN KEY (TAG_ID) REFERENCES RW_TAG (TAG_ID)
);

CREATE TABLE RW_ATTACHMENT (
    ATTACH_ID NUMBER PRIMARY KEY,
    POST_ID NUMBER NOT NULL,
    UPLOADER_ID NUMBER NOT NULL,
    ORIGINAL_NAME VARCHAR2(255) NOT NULL,
    SAVED_NAME VARCHAR2(255) NOT NULL,
    FILE_PATH VARCHAR2(400) NOT NULL,
    FILE_SIZE NUMBER DEFAULT 0 NOT NULL,
    FILE_EXT VARCHAR2(20),
    MIME_TYPE VARCHAR2(120),
    IMAGE_YN CHAR(1) DEFAULT 'N' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_RW_ATTACHMENT_POST FOREIGN KEY (POST_ID) REFERENCES RW_POST (POST_ID),
    CONSTRAINT FK_RW_ATTACHMENT_USER FOREIGN KEY (UPLOADER_ID) REFERENCES RW_USER (USER_ID)
);

CREATE TABLE RW_NOTIFICATION (
    NOTI_ID NUMBER PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    NOTI_TYPE VARCHAR2(50),
    TITLE VARCHAR2(200) NOT NULL,
    MESSAGE VARCHAR2(1000) NOT NULL,
    TARGET_URL VARCHAR2(300),
    READ_YN CHAR(1) DEFAULT 'N' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_RW_NOTIFICATION_USER FOREIGN KEY (USER_ID) REFERENCES RW_USER (USER_ID)
