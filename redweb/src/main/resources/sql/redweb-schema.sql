CREATE TABLE RW_USER_AUTH_LOG (
    AUTH_LOG_ID NUMBER PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    LOGIN_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    LOGIN_IP VARCHAR2(64),
    USER_AGENT VARCHAR2(500),
    LOGIN_RESULT VARCHAR2(20),
    CONSTRAINT FK_RW_USER_AUTH_LOG_USER FOREIGN KEY (USER_ID) REFERENCES RW_USER (USER_ID)
);

CREATE TABLE RW_REPORT (
    REPORT_ID NUMBER PRIMARY KEY,
    REPORTER_ID NUMBER NOT NULL,
    TARGET_TYPE VARCHAR2(30) NOT NULL,
    TARGET_ID NUMBER NOT NULL,
    REASON_CODE VARCHAR2(50),
    REASON_DETAIL VARCHAR2(1000),
    STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    PENALTY_SUMMARY VARCHAR2(300),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    PROCESSED_BY NUMBER,
    PROCESSED_AT TIMESTAMP,
    CONSTRAINT FK_RW_REPORT_USER FOREIGN KEY (REPORTER_ID) REFERENCES RW_USER (USER_ID)
);

CREATE TABLE RW_MESSAGE (
    MESSAGE_ID NUMBER PRIMARY KEY,
    SENDER_USER_ID NUMBER NOT NULL,
    RECEIVER_USER_ID NUMBER NOT NULL,
