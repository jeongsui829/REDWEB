MERGE INTO RW_USER T
USING (
    SELECT 4 USER_ID, 'user3' LOGIN_ID, 'LOCAL_DEMO_PASSWORD_REQUIRED' PASSWORD_HASH, UNISTR('\C720\C800\0033') USER_NAME, 'user3' NICKNAME, 'user3@redweb.local' EMAIL, '010-3333-1103' PHONE FROM DUAL
    UNION ALL SELECT 5, 'user4', 'LOCAL_DEMO_PASSWORD_REQUIRED', UNISTR('\C720\C800\0034'), 'user4', 'user4@redweb.local', '010-3333-1104' FROM DUAL
    UNION ALL SELECT 6, 'user5', 'LOCAL_DEMO_PASSWORD_REQUIRED', UNISTR('\C720\C800\0035'), 'user5', 'user5@redweb.local', '010-3333-1105' FROM DUAL
    UNION ALL SELECT 7, 'user6', 'LOCAL_DEMO_PASSWORD_REQUIRED', UNISTR('\C720\C800\0036'), 'user6', 'user6@redweb.local', '010-3333-1106' FROM DUAL
) S
ON (T.LOGIN_ID = S.LOGIN_ID)
WHEN MATCHED THEN UPDATE SET
    T.PASSWORD_HASH = S.PASSWORD_HASH,
    T.USER_NAME = S.USER_NAME,
    T.NICKNAME = S.NICKNAME,
    T.EMAIL = S.EMAIL,
    T.PHONE = S.PHONE,
    T.STATUS = 'ACTIVE',
    T.ROLE_CODE = 'MEMBER',
    T.EMAIL_VERIFIED_YN = 'Y',
    T.SECURITY_QUESTION = UNISTR('\AC00\C7A5\0020\AE30\C5B5\C5D0\0020\B0A8\B294\0020\C5EC\D589\C9C0\B294\003F'),
    T.SECURITY_ANSWER = UNISTR('\AD0C'),
    T.UPDATED_AT = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT (
    USER_ID, LOGIN_ID, PASSWORD_HASH, USER_NAME, NICKNAME, EMAIL, PHONE,
    PROFILE_IMAGE_PATH, STATUS, ROLE_CODE, EMAIL_VERIFIED_YN,
    SECURITY_QUESTION, SECURITY_ANSWER, CREATED_AT, UPDATED_AT
) VALUES (
    S.USER_ID, S.LOGIN_ID, S.PASSWORD_HASH, S.USER_NAME, S.NICKNAME, S.EMAIL, S.PHONE,
    '/assets/images/profile-default.png', 'ACTIVE', 'MEMBER', 'Y',
    UNISTR('\AC00\C7A5\0020\AE30\C5B5\C5D0\0020\B0A8\B294\0020\C5EC\D589\C9C0\B294\003F'),
    UNISTR('\AD0C'), SYSTIMESTAMP, SYSTIMESTAMP
);

DECLARE
    v_count NUMBER;
    v_start NUMBER;
BEGIN
    SELECT GREATEST(NVL(MAX(USER_ID), 0) + 1, 1000) INTO v_start FROM RW_USER;
    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_RW_USER';
    IF v_count > 0 THEN
        EXECUTE IMMEDIATE 'DROP SEQUENCE SEQ_RW_USER';
    END IF;
    EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_RW_USER START WITH ' || v_start || ' INCREMENT BY 1 NOCACHE';
END;
/

COMMIT;
